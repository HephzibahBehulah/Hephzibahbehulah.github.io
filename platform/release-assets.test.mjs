import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {copySharedAssets} from './release-assets.mjs';

test('release copies shared JavaScript, CSS, and favicon into the output',()=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'hb-release-'));
 const output=path.join(root,'dist');
 fs.mkdirSync(path.join(root,'js','nested'),{recursive:true});
 fs.mkdirSync(path.join(root,'packages/shared-ui/css'),{recursive:true});
 fs.mkdirSync(path.join(root,'packages/shared-ui/assets'),{recursive:true});
 fs.mkdirSync(path.join(root,'packages/shared-ui/js'),{recursive:true});
 fs.mkdirSync(path.join(root,'packages/shared-i18n'),{recursive:true});
 fs.mkdirSync(path.join(root,'apps/terminal'),{recursive:true});
 fs.mkdirSync(path.join(root,'apps/admin'),{recursive:true});
 fs.mkdirSync(output);
 fs.writeFileSync(path.join(root,'js','nested','app.js'),'export {};');
 fs.writeFileSync(path.join(root,'packages/shared-ui/css','site.css'),'body{}');
 fs.writeFileSync(path.join(root,'packages/shared-ui/assets','logo.svg'),'<svg/>');
 fs.writeFileSync(path.join(root,'packages/shared-ui/js','ai-lab.js'),'globalThis.aiLab=true;');
 fs.writeFileSync(path.join(root,'packages/shared-i18n','language-system.js'),'globalThis.language=true;');
 fs.writeFileSync(path.join(root,'apps/terminal','adigun-agent.js'),'globalThis.agent=true;');
 fs.writeFileSync(path.join(root,'apps/admin','adigun-github-knowledge.js'),'globalThis.adminKnowledge=true;');
 fs.writeFileSync(path.join(root,'apps/admin','adigun-sidebar.js'),'globalThis.adminSidebar=true;');
 fs.writeFileSync(path.join(root,'favicon.ico'),Buffer.from([0,0,1,0,0,0]));
 copySharedAssets(root,output);
 assert.equal(fs.readFileSync(path.join(output,'js','nested','app.js'),'utf8'),'export {};');
 assert.equal(fs.readFileSync(path.join(output,'css','site.css'),'utf8'),'body{}');
 assert.equal(fs.readFileSync(path.join(output,'assets','logo.svg'),'utf8'),'<svg/>');
 assert.equal(fs.readFileSync(path.join(output,'js','ai-lab.js'),'utf8'),'globalThis.aiLab=true;');
 assert.equal(fs.readFileSync(path.join(output,'js','language-system.js'),'utf8'),'globalThis.language=true;');
 assert.equal(fs.readFileSync(path.join(output,'js','adigun-agent.js'),'utf8'),'globalThis.agent=true;');
 assert.equal(fs.readFileSync(path.join(output,'js','adigun-github-knowledge.js'),'utf8'),'globalThis.adminKnowledge=true;');
 assert.equal(fs.readFileSync(path.join(output,'js','adigun-sidebar.js'),'utf8'),'globalThis.adminSidebar=true;');
 assert.deepEqual(fs.readFileSync(path.join(output,'favicon.ico')),Buffer.from([0,0,1,0,0,0]));
 fs.rmSync(root,{recursive:true,force:true});
});
