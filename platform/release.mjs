import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const run=(command,args,cwd=root)=>{const result=spawnSync(command,args,{cwd,stdio:'inherit',shell:process.platform==='win32'&&!path.isAbsolute(command)});if(result.error)throw result.error;if(result.status!==0)throw Error(command+' '+args.join(' ')+' failed with status '+result.status);};
const node=(...args)=>run(process.execPath,args);
node('platform/check-deployment-contract.mjs');
const tests=fs.readdirSync(path.join(root,'platform')).filter(name=>name.endsWith('.test.mjs')).sort().map(name=>path.join('platform',name));
node('--test',...tests);
node('platform/check-browser-scripts.mjs');
const cyber=path.join(root,'apps/pentest-source');
run('python',['-m','pip','install','--disable-pip-version-check','Pillow'],cyber);
run('python',['core/build_app.py','--out','build-app/web','--download-runtime'],cyber);
node('platform/build.mjs','apps/pentest-source/build-app/web');
node('platform/prepare-config.mjs');
console.log('Release build complete. Cloudflare deploy runs as the configured deploy command.');
