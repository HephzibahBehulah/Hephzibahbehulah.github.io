import fs from 'node:fs';
import {spawnSync} from 'node:child_process';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const run=(command,args,cwd=root)=>{const result=spawnSync(command,args,{cwd,stdio:'inherit',shell:process.platform==='win32'});if(result.error)throw result.error;if(result.status!==0)throw Error(command+' '+args.join(' ')+' failed with status '+result.status);};
const node=(...args)=>run(process.execPath,args);
const engineering=path.join(root,'platform-source/engineering');
const plc=path.join(engineering,'apps/voltpro-plc');
const cyber=path.join(root,'apps/pentest-source');
node('platform/check-browser-scripts.mjs');
node('--test','platform/access.test.mjs','platform/router.test.mjs','platform/engineering-ai.test.mjs','platform/app-archives.test.mjs','platform/admin-accounts.test.mjs','platform/public-auth.test.mjs','platform/studio-bank.test.mjs');
node('platform/fetch-apps.mjs');
run('npm',['ci','--no-audit','--no-fund'],plc);
run('npm',['test'],plc);
run('npm',['run','build'],plc);
if(!fs.existsSync(path.join(engineering,'voltpro-plc/index.html')))throw Error('PLC build did not produce the integrated /voltpro-plc/ site.');
run('python',['-m','pip','install','--disable-pip-version-check','Pillow'],cyber);
run('python',['core/build_app.py','--out','build-app/web','--download-runtime'],cyber);
node('platform/build-electcad.mjs');
node('platform/studio-bank-check.mjs');
node('platform/studio-plc-check.mjs');
node('platform/build.mjs','platform-source/engineering','apps/pentest-source/build-app/web');
node('platform/prepare-config.mjs');
console.log('Release build complete. Cloudflare deploy runs as the configured deploy command.');
